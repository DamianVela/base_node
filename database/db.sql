Latitud DECIMAL(10,7) NOT NULL
)
GO

CREATE TABLE PERSONAL(
IdPersona INT PRIMARY KEY IDENTITY,
Celular VARCHAR(16),
ApellidoPaterno VARCHAR(32) NOT NULL,
ApellidoMaterno VARCHAR(32) NOT NULL,
Nombres VARCHAR(64) NOT NULL,
Usuario VARCHAR(20) NOT NULL UNIQUE,
Clave VARCHAR(255),
FechaExpiracionClave DATE,
IdRol INT REFERENCES ROLES(IdRol) NOT NULL,
Activo BIT NOT NULL DEFAULT 1,
Mail VARCHAR(64),
FechaCreacion DATETIME NOT NULL DEFAULT GETDATE(),
FechaIngreso DATETIME NOT NULL,
RutaImagen VARCHAR(2048),
FechaNacimiento DATE,
RFC VARCHAR(64),
NumEmpleado INT,
NumImss VARCHAR(16),
Curp VARCHAR(32),
IdUbicacion INT REFERENCES UBICACIONES(IdUbicacion)
)
GO

