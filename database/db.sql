CREATE TABLE UBICACIONES(
IdUbicacion INT PRIMARY KEY IDENTITY,
Pais VARCHAR(32) NOT NULL,
Estado VARCHAR(32) NOT NULL,
Calle VARCHAR(32),
Municipio VARCHAR(32),
Colonia VARCHAR(32),
CodigoPostal VARCHAR(16),
NumeroExterior VARCHAR(16),
